import frappe
from frappe.utils import cint, flt

IGNORE_PROPS = {
	"name", "doctype", "docstatus", "dt", "fieldname",
	"modified", "creation", "owner", "modified_by", "idx",
}

SKIP_ON_UPDATE = {"insert_after"}

LINK_TYPES = ("Link", "Table", "Table MultiSelect")


def execute():
	rows = CUSTOM_FIELDS

	unique = {}
	for row in rows:
		unique[(row["dt"], row["fieldname"])] = row

	cf_meta = frappe.get_meta("Custom Field")
	valid_props = {df.fieldname: df for df in cf_meta.fields}

	stats = {"created": 0, "updated": 0, "unchanged": 0, "skipped": 0, "failed": 0}
	touched_doctypes = set()

	def process(row, force=False):
		dt, fn = row["dt"], row["fieldname"]

		if not frappe.db.exists("DocType", dt):
			return skip(f"{dt}-{fn}: DocType '{dt}' not found")

		if frappe.db.exists("DocField", {"parent": dt, "fieldname": fn}):
			return skip(f"{dt}-{fn}: a standard field with this name already exists")

		options = row.get("options")
		if row.get("fieldtype") in LINK_TYPES and options and not frappe.db.exists("DocType", options):
			return skip(f"{dt}-{fn}: linked DocType '{options}' not found")

		values = {
			k: v for k, v in row.items()
			if k not in IGNORE_PROPS and k in valid_props
		}

		module = values.get("module")
		if module and not frappe.db.exists("Module Def", module):
			values.pop("module")

		existing = frappe.db.get_value("Custom Field", {"dt": dt, "fieldname": fn}, "name")

		try:
			if existing:
				update(existing, values, valid_props)
			else:
				if force:
					values.pop("insert_after", None)
				create(dt, fn, values)
			touched_doctypes.add(dt)
		except Exception:
			stats["failed"] += 1
			frappe.log_error(title=f"Custom Field sync failed: {dt}-{fn}")
			print(f"FAILED  {dt}-{fn} (see Error Log)")

	def create(dt, fn, values):
		doc = frappe.get_doc({"doctype": "Custom Field", "dt": dt, "fieldname": fn, **values})
		doc.insert(ignore_permissions=True)
		stats["created"] += 1
		print(f"CREATED {dt}-{fn}")

	def update(name, values, valid_props):
		doc = frappe.get_doc("Custom Field", name)
		changes = {}
		for key, new in values.items():
			if key in SKIP_ON_UPDATE and doc.get(key):
				continue
			if normalize(doc.get(key), valid_props[key].fieldtype) != normalize(new, valid_props[key].fieldtype):
				changes[key] = new

		if not changes:
			stats["unchanged"] += 1
			return

		doc.update(changes)
		doc.save(ignore_permissions=True)
		stats["updated"] += 1
		print(f"UPDATED {name}: {', '.join(sorted(changes))}")

	def skip(msg):
		stats["skipped"] += 1
		print(f"SKIPPED {msg}")


	pending = list(unique.values())
	while pending:
		deferred, progressed = [], False
		for row in pending:
			if insert_after_ready(row):
				process(row)
				progressed = True
			else:
				deferred.append(row)

		if not progressed:
			for row in deferred:
				print(f"NOTE    {row['dt']}-{row['fieldname']}: insert_after '{row.get('insert_after')}' not found, placing at end")
				process(row, force=True)
			break
		pending = deferred

	for dt in touched_doctypes:
		frappe.clear_cache(doctype=dt)
	frappe.db.commit()

	print("Custom field sync:", stats)


def insert_after_ready(row):
	target = row.get("insert_after")
	if not target:
		return True
	dt = row["dt"]
	return bool(
		frappe.db.exists("DocField", {"parent": dt, "fieldname": target})
		or frappe.db.exists("Custom Field", {"dt": dt, "fieldname": target})
	)


def normalize(value, fieldtype):
	"""Treat None / '' / 0 consistently so we don't flag false differences."""
	if fieldtype in ("Check", "Int"):
		return cint(value)
	if fieldtype in ("Float", "Currency", "Percent"):
		return flt(value)
	if value is None or value == "":
		return None
	return str(value)


